import assert from 'node:assert/strict';
import {chartGeometry} from '../assets/procedure-chart.mjs';
const fix=(id,lat,lon)=>({id,lat,lon});
const leg=(id,path,missed=false)=>({path,missed,point:id?fix(id,38+id.charCodeAt(0)/100,-90):null});
const group=legs=>({legs});
const result=chartGeometry([group([leg('A','IF'),leg('B','TF'),leg(null,'CA',true),leg('C','DF'),leg('D','TF')])]);
assert.deepEqual(result.segments.map(s=>s.map(p=>p.id)),[['A','B']],'Missed phase remains excluded after its first flag');
assert.deepEqual(result.fixes.map(p=>p.id),['A','B']);
const gap=chartGeometry([group([leg('A','IF'),leg('B','TF'),leg('C','RF'),leg('D','TF'),leg('E','TF')])]);
assert.deepEqual(gap.segments.map(s=>s.map(p=>p.id)),[['A','B'],['D','E']],'No invented connector across an arc');
assert.deepEqual(gap.omitted,['RF']);
const transition=chartGeometry([group([leg('A','IF'),leg('B','TF')]),group([leg('B','IF'),leg('C','TF')])]);
assert.equal(transition.segments.length,2);
assert.deepEqual(transition.fixes.map(p=>p.id),['A','B','C'],'Shared transition fix is labeled once');
const disjoint=chartGeometry([group([leg('A','IF'),leg('B','TF'),leg('D','IF'),leg('E','TF')])]);
assert.deepEqual(disjoint.segments.map(s=>s.map(p=>p.id)),[['A','B'],['D','E']]);
assert.equal(chartGeometry([group([leg(null,'IF'),leg('A','TF')])]).segments.length,0);
assert.equal(chartGeometry([group([{path:'IF',point:{lat:NaN,lon:0}},leg('A','TF')])]).segments.length,0);
console.log('Procedure chart passed: resolved segments, phase-latched missed approach exclusion, arc/vector discontinuities, shared-fix labels and invalid coordinates.');
