import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {measure}=createRequire(import.meta.url)('../assets/map-tools.js');
const east=measure({lat:0,lng:0},{lat:0,lng:1});
assert.ok(Math.abs(east.distance-60.04046)<.001);
assert.equal(east.bearing,90);
assert.equal(measure({lat:0,lng:1},{lat:0,lng:0}).bearing,270);
const north=measure({lat:0,lng:0},{lat:1,lng:0});
assert.equal(north.bearing,0);
assert.ok(Math.abs(north.distance-east.distance)<.001);
const seam=measure({lat:0,lng:179},{lat:0,lng:-179});
assert.ok(Math.abs(seam.distance-120.08092)<.001);
assert.equal(seam.bearing,90);
assert.ok(seam.points.every((point,i)=>!i||Math.abs(point[1]-seam.points[i-1][1])<1));
assert.equal(measure({lat:47,lng:-97},{lat:47,lng:-97}).bearing,null);
assert.equal(measure({lat:0,lng:0},{lat:0,lng:180}).bearing,null);
assert.throws(()=>measure({lat:91,lng:0},{lat:0,lng:0}));
assert.throws(()=>measure({lat:0,lng:NaN},{lat:0,lng:0}));
console.log('Map ruler checks passed: known distances and true bearings, dateline, identical/antipodal points, and invalid coordinates.');

