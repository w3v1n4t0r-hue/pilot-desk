import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const S=createRequire(import.meta.url)('../assets/chart-symbols.js');
const kinds=p=>S.pirep(p).items.map(x=>x.kind);
assert.equal(S.pirep({tbInt1:'LGT-MOD'}).items[0].displayLevel,2);
assert.equal(S.pirep({rawOb:'AAA UUA /TB SEV TURB /IC MOD RIME'}).urgent,true);
assert.deepEqual(kinds({rawOb:'AAA UA /TB LGT /IC MOD /WX TSRA /SK BKN030'}),['icing','turbulence']);
assert.equal(S.pirep({rawOb:'AAA UA /TB NEG'}).items[0].negative,true);
assert.equal(S.pirep({rawOb:'AAA UA /IC NEG'}).items[0].negative,true);
assert.equal(S.pirep({rawOb:'AAA UA /TB CHOP'}).items[0].displayLevel,null);
assert.equal(S.pirep({rawOb:'AAA UA /TB CONS LT OCNL MOD'}).items[0].displayLevel,2);
assert.equal(S.pirep({icInt1:'TRC'}).items[0].displayLevel,1);
assert.equal(S.pirep({rawOb:'AAA UA /TB EXTRM'}).items[0].displayLevel,4);
assert.deepEqual(kinds({rawOb:'AAA UA /RM NO TURB REPORTED'}),['skyweather']);
assert.deepEqual(kinds({rawOb:'AAA UA /WX -RASN'}),['skyweather']);
assert.deepEqual(kinds({rawOb:'AAA UA /WX GR'}),['skyweather']);
assert.deepEqual(kinds({rawOb:'AAA UA /WX FG'}),['skyweather']);
assert.deepEqual(kinds({rawOb:'AAA UA /SK SKC'}),['skyweather']);
assert.deepEqual(kinds({rawOb:'AAA UA /SK SKC BKN100'}),['skyweather']);
assert.deepEqual(kinds({}),['skyweather']);
assert.equal(S.navigation('navaids',{TYPE:'NDB'}).kind,'ndb');
for(const key of ['airports','navaids','fixes','obstacles']){const icon=S.navigation(key);assert.ok(icon.html.includes('<svg'));assert.ok(!icon.html.includes('<span'));}
assert.ok(!S.pirep({tbInt1:'<script>alert(1)</script>'}).html.includes('<script>'));
assert.equal(S.pirep({tbInt1:'SEV'}).urgent,true);
assert.equal(S.pirep({tbInt1:'MOD'}).urgent,false);
assert.ok(S.pirep({fltlvl:80}).html.includes('080'));
assert.ok(!S.pirep({fltlvl:-1}).html.includes('rp-pirep-altitude'));
assert.ok(!S.pirep({}).html.includes('rp-pirep-altitude'));
assert.ok(S.weatherSvg('icing',2).includes('#5145ff'));
assert.ok(S.weatherSvg('turbulence',2).includes('#ff8500'));
for(const kind of ['icing','turbulence'])for(const level of [1,2,3])assert.ok(S.weatherSvg(kind,level).includes('<path d='));
assert.notEqual(S.weatherSvg('turbulence',3),S.weatherSvg('turbulence',4));
console.log('Chart symbol tests passed: multi-condition PIREPs, intensities, negative vs unknown, weather, sky, navigation, and safe markup.');

assert.equal(S.pirep({rawOb:'AAA UA /IC MDT'}).items[0].level,2);
assert.equal(S.pirep({rawOb:'AAA UA /TB SVR'}).items[0].level,3);
assert.equal(S.pirep({rawOb:'AAA UA /IC TR'}).items[0].level,.5);
for(const [type,kind] of [['VOR','navaid'],['VOR/DME','vordme'],['VORTAC','vortac'],['DME','dme'],['NDB','ndb']])assert.equal(S.navigation('navaids',{TYPE:type}).kind,kind);
assert.equal(S.navigation('airports',{TYPE:'HELIPORT'}).kind,'heliport');
const now=Date.parse('2026-10-02T18:00:00Z');
assert.match(S.reportTime({obsTime:now/1000-1800},now),/30 min ago/);
assert.match(S.reportTime({obsTime:'2026-10-02T15:00:00Z'},now),/Older report/);
assert.equal(S.reportTime({},now),'Observation time unavailable');
assert.equal(S.reportTime({obsTime:'invalid'},now),'Observation time unavailable');
assert.equal(S.reportTime({obsTime:now+600000},now),'Observation time unavailable');

assert.equal(S.reportTime({receiptTime:now/1000},now),'Observation time unavailable');
