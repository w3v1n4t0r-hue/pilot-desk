import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = path => fs.readFileSync(path, 'utf8');
const home = read('src/pages/index.astro');
const feature = read('src/components/ScrollFlightPath.astro');
const css = read('assets/scrollcraft/pilotdesk-home.css');
const upstream = read('assets/scrollcraft/scrollcraft.js');
const upstreamCss = read('assets/scrollcraft/scrollcraft.css');
const boot = read('assets/scrollcraft/pilotdesk-home.js');
assert(read('assets/scrollcraft/LICENSE').includes('MIT License'));
assert.match(home, /import ScrollFlightPath/);
assert.match(home, /<ScrollFlightPath \/>/);
assert.match(home, /\/assets\/scrollcraft\/scrollcraft\.js/);
assert.match(home, /\/assets\/scrollcraft\/scrollcraft\.css/);
assert.match(home, /\/assets\/scrollcraft\/pilotdesk-home\.css/);
assert.match(home, /\/assets\/scrollcraft\/pilotdesk-home\.js/);
assert(home.indexOf('<ScrollFlightPath />') > home.indexOf('id="pdHomeTitle"'));
assert(home.indexOf('<ScrollFlightPath />') < home.indexOf('pd-home-crosswind'));
assert(home.indexOf('pd-home-crosswind') < home.indexOf('id="popular-tools"'));
assert(home.indexOf('pd-home-weather') < home.indexOf('flight-lessons-title'));
assert.match(home, /action="\/route-planner\.html" method="get"/);
for (const id of ['pdHomeWind','pdHomeCross','pdHomeHead','pdHomeDesk','pdHomeDeskItems']) {
  assert(home.includes('id="'+id+'"'), 'homepage retained '+id);
}
assert.match(feature, /data-sc-act="pin" data-sc-span="1\.35"/);
assert.match(feature, /data-sc-parallax="-0\.06"/);
assert.match(feature, /pd-sc-plane/);
assert.match(feature, /href="\/route-planner\.html"/);
assert.match(feature, /href="\/weather\.html"/);
assert.match(feature, /href="\/e6b-flight-computer\.html"/);
assert(!/EXAMPLE ROUTE|NOT LIVE FLIGHT DATA|example flight path/i.test(feature));
assert.match(feature, /not a navigation chart/);
assert.match(css, /max-width:600px/);
assert.match(css, /prefers-reduced-motion:reduce/);
assert.match(css, /position:relative!important/);
assert.match(boot, /navigator\.connection\?\.saveData/);
assert.match(boot, /ScrollCraft\.mount\(root\)/);
assert.match(upstream, /global\.ScrollCraft = \{ mount: mount/);
assert.match(upstreamCss, /\.sc-stage/);
new vm.Script(upstream, {filename:'scrollcraft.js'});
new vm.Script(boot, {filename:'pilotdesk-home.js'});
console.log('Scrollcraft homepage structure, useful controls, performance fallback, and engine syntax passed.');
