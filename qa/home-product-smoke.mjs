import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=path=>fs.readFileSync(path,'utf8');
const home=read('src/pages/index.astro');
const css=read('assets/home-product.css');
const motion=read('assets/motion-polish.js');
assert.match(home,/href="\/assets\/home-product\.css"/);
assert.match(home,/class="pd-home-product"/);
assert.match(home,/ROUTE SCHEMATIC/);
assert.match(home,/NOT LIVE FLIGHT DATA/);
assert.match(home,/aria-label="Stylized route graphic\. This is not an actual aviation chart or live route\."/);
assert.match(home,/href="\/route-planner\.html"/);
assert.equal((home.match(/id="pdHomeWind"/g)||[]).length,1,'retain one functional crosswind control');
assert.equal((home.match(/id="pdHomeCross"/g)||[]).length,1);
assert.equal((home.match(/id="pdHomeHead"/g)||[]).length,1);
assert(home.indexOf('class="pd-home-crosswind"')>home.indexOf('class="pd-home-desk"'),'crosswind should follow returning-user desk');
assert(home.indexOf('class="pd-home-product"')<home.indexOf('class="pd-home-proof"'),'show product above the fold');
for(const link of ['/weather.html','/tools.html','/daily/','/flight-training.html'])
  assert(home.includes(`href="${link}"`),`retain ${link}`);
assert.match(css,/max-width:480px/);
assert.match(css,/max-width:820px/);
assert.match(css,/prefers-reduced-motion:no-preference/);
assert.match(css,/\.pd-home-product-track/);
assert.doesNotMatch(css,/backdrop-filter|filter:blur|position:fixed/,'no expensive visual effects');
assert.match(motion,/querySelector\('\.pd-home-product'\)/);
new vm.Script(read('assets/home-desk.js'));
new vm.Script(motion);
console.log('Homepage visual refresh checks passed: visible product preview, working crosswind preserved, clear example label, responsive CSS and motion guard.');
