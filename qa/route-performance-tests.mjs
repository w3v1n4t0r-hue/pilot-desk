import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),N=require('../assets/navlog-core.js');
const points=[{id:'A',lat:0,lon:0},{id:'B',lat:1,lon:0},{id:'C',lat:2,lon:0}];
const options={tas:120,burn:10,windFrom:0,windSpeed:0};
const uniform=N.build(points,options);
const varied=N.build(points,{...options,legInputs:[{}, {tas:60,burn:8,windFrom:180,windSpeed:20}]});
assert.equal(varied.legs[0].tas,120);assert.equal(varied.legs[1].gs,80);assert.equal(varied.legs[1].burn,8);
assert.ok(varied.totalHours>uniform.totalHours);
assert.throws(()=>N.build(points,{...options,legInputs:[{tas:0}]}));
assert.throws(()=>N.build(points,{...options,legInputs:[{windFrom:361}]}));
const nav={totalFuel:20,totalHours:2,legs:[{to:'B',cumFuel:10,cumTime:1},{to:'C',cumFuel:20,cumTime:2}]};
const plan=N.fuelPlan(nav,{onboard:40,taxi:1,alternate:3,reserveMinutes:45,reserveBurn:10,extra:2,departureUtc:'2026-09-30T23:30Z'});
assert.equal(plan.required,33.5);assert.equal(plan.landing,19);assert.equal(plan.margin,6.5);
assert.equal(new Date(plan.arrival).toISOString(),'2026-10-01T01:30:00.000Z');
assert.equal(plan.legs[0].fuelRemaining,29);
assert.equal(N.fuelPlan(nav,{taxi:0,alternate:0,reserveMinutes:0,reserveBurn:10}).margin,null);
assert.equal(N.fuelPlan(nav,{onboard:5,taxi:1,reserveMinutes:45,reserveBurn:10}).landing,-16);
assert.throws(()=>N.fuelPlan(nav,{onboard:NaN,reserveMinutes:45,reserveBurn:10}));
assert.throws(()=>N.fuelPlan(nav,{taxi:-1,reserveMinutes:45,reserveBurn:10}));
assert.throws(()=>N.fuelSettingsPlan(nav,{reserveMinutes:'',taxi:'0',alternate:'0',extra:'0'},10));
assert.throws(()=>N.fuelPlan(nav,{reserveMinutes:45,reserveBurn:10,departureUtc:'2026-09-30T23:30'}));
const overrides={'A,0.00000,0.00000>B,1.00000,0.00000':{tas:'95',windFrom:'',windSpeed:'15'}};
assert.deepEqual(N.legOverridesToInputs(points,overrides),[{tas:95,windSpeed:15},{}]);
assert.deepEqual(N.legOverridesToInputs([points[1],points[0]],overrides),[{}]);
console.log('Route performance tests passed: leg overrides, fuel ledger, shortage, unknown onboard, UTC midnight, invalid inputs, and changed-route isolation.');
