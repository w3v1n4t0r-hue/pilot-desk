import assert from 'node:assert/strict';
import fs from 'node:fs';
import {runwayGeometry,symbolRecord,symbolSvg,visibleAirports} from '../assets/airport-symbol-core.mjs';
const airport={id:'TEST',lat:0,lon:0,type:'A',use:'PU',status:'O',runways:[{id:'09/27',lengthFt:4000,ends:[{latitude:0,longitude:-.01},{latitude:0,longitude:.01}]}],frequencies:[]};
assert.deepEqual(runwayGeometry(airport),[[3.5,12,20.5,12]],'East-west runway retains geographic direction');
assert.deepEqual(runwayGeometry({...airport,runways:[{id:'18/36',ends:[{latitude:.01,longitude:0},{latitude:-.01,longitude:0}]}]}),[[12,3.5,12,20.5]],'North-south runway retains direction');
assert.deepEqual(runwayGeometry({...airport,runways:[{id:'H1',ends:[{},{}]}]}),[]);
assert.deepEqual(runwayGeometry({...airport,runways:[{id:'09/27',ends:[{latitude:null,longitude:0},{latitude:0,longitude:1}]}]}),[],'Missing coordinates never become zero');
assert.equal(symbolRecord({...airport,frequencies:[{service:'ATIS'}]}).tower,false,'ATIS alone does not imply tower');
assert.equal(symbolRecord({...airport,frequencies:[{service:'LCL/P'}]}).tower,true);
const source=JSON.parse(fs.readFileSync('data/airports/symbols.json'));
assert.equal(source.records.length,JSON.parse(fs.readFileSync('data/airports/manifest.json')).count);
const sample=id=>source.records.find(a=>a.id===id);
assert.equal(sample('KGFK').lines.length,4,'Helipads excluded from land runway glyph');
assert.equal(sample('KRDM').tower,true);assert.equal(sample('KBJI').tower,false);
assert.match(symbolSvg(sample('KGFK')),/#39b8f2/);assert.match(symbolSvg(sample('KBJI')),/#df40d9/);
assert.match(symbolSvg({...sample('KGFK'),status:'CP'}),/M6 6l12 12/);
const b={south:-1,north:1,west:-1,east:1},record=symbolRecord(airport);
assert.equal(visibleAirports([record],b,4).length,0);
assert.equal(visibleAirports([record],b,8,[]).length,0);
assert.equal(visibleAirports([record],b,6).length,1);
assert.equal(visibleAirports([record],b,8).length,1);
assert.equal(visibleAirports([{...record,lon:2}],b,12).length,0);
assert.equal(visibleAirports([{...record,use:'PR'}],b,9).length,0);
assert.equal(visibleAirports([{...record,use:'PR'}],b,10,['aero/privateAP']).length,1);
assert.equal(visibleAirports([{...record,type:'B'}],b,10,['aero/seaplane']).length,1);
console.log('Airport symbols passed: geographic geometry, source join, tower evidence, examples, closed/private/seaplane states, viewport and zoom filters.');
