import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const V=createRequire(import.meta.url)('../assets/map-view.js');
const view={lon:-97.19218,lat:47.95269,zoom:13,chart:'sectional'};
assert.deepEqual(V.parse(V.format(view)),view);
assert.equal(V.parse('#rpPerformance'),null);
for(const hash of ['#map=/0/4','#map=NaN/0/4','#map=181/0/4','#map=0/86/4','#map=0/0/15','#map=0/0/4/unknown','#map=0/0/4?secret=1'])assert.equal(V.parse(hash),null);
assert.equal(V.validate({lon:'0',lat:0,zoom:4}),null);
assert.equal(V.format({lon:0,lat:Infinity,zoom:4}),null);
const stored={lon:-120,lat:35,zoom:6};
const storage={getItem:()=>JSON.stringify(stored)};
assert.deepEqual(V.read(V.format(view),storage),view);
assert.deepEqual(V.read('',storage),stored);
assert.equal(V.read('',{getItem:()=>'{broken'}),null);
assert.equal(V.read('',{getItem(){throw Error('Blocked')}}),null);
assert.equal(V.read('',{getItem:()=>JSON.stringify({lon:300,lat:0,zoom:5})}),null);
assert.deepEqual(V.enabled({radar:false,metar:true},{radar:'false',metar:false,unknown:true}),{radar:false,metar:false});
assert.equal(V.opacity(NaN,.68,.2),.68);
assert.equal(V.opacity('0.6',.68,.2),.68);
assert.equal(V.opacity(9,.68,.2),1);
assert.equal(V.opacity(-1,.68,.2),.2);
console.log('Map-view checks passed: URL round trip, boundaries, precedence, corrupt/blocked storage, strict overlay booleans and opacity bounds.');
